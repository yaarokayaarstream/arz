/**
 * Builds standard Stalker / MAG M3U text with VLC/TiviMate compatible user-agent and MAC cookies.
 */
function buildStalkerM3uText(channels: StreamChannel[], mac: string, portalUrl: string): string {
  let m3u = '#EXTM3U x-tvg-url=""\r\n';
  m3u += `## Generated by Yaaro Ka Yaar Stream Hub (Stalker MAG Engine)\r\n`;
  m3u += `## Stalker Portal: ${portalUrl}\r\n`;
  m3u += `## Target MAC: ${mac}\r\n\r\n`;

  for (const ch of channels) {
    const logo = ch.stream_icon ? ` tvg-logo="${ch.stream_icon}"` : '';
    const tvgId = ch.epg_channel_id ? ` tvg-id="${ch.epg_channel_id}"` : '';
    const group = ch.category_name ? ` group-title="${ch.category_name}"` : ' group-title="Live TV"';
    m3u += `#EXTINF:-1${tvgId}${logo}${group},${ch.name}\r\n`;
    m3u += `#EXTVLCOPT:http-user-agent=Mozilla/5.0 (QtEmbedded; U; Linux; C) AppleWebKit/533.3 (KHTML, like Gecko) MAG200 stbapp ver: 2 rev: 250 Safari/533.3\r\n`;
    m3u += `#EXTVLCOPT:http-header=Cookie: mac=${mac}\r\n`;
    m3u += `${ch.direct_source}\r\n\r\n`;
  }

  return m3u;
}

